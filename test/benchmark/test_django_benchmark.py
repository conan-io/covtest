"""Django benchmark for covtest.

Django's test suite is normally run via ``python tests/runtests.py``, which
handles two things that plain ``pytest`` needs to do itself:

  1. Adds ``tests/`` to ``sys.path`` so that ``test_sqlite`` (the bundled
     minimal SQLite settings file) can be imported.
  2. Sets ``DJANGO_SETTINGS_MODULE`` so Django knows which settings to load.

We can't use ``runtests.py`` directly because the benchmark needs
``--json-report`` to collect structured pass/fail results per test node ID,
and that flag is not supported by the custom runner.

Instead, the ``_django_setup`` hook writes a ``pytest.ini`` into the cloned
repo root once, before any test runs.  That file tells ``pytest-django``
which settings module to use and adds ``tests/`` to ``pythonpath``, so every
subsequent ``pytest`` invocation picks up the config automatically — no extra
CLI flags or environment variables needed.
"""

import os

import pytest

from covtest.util.files import chdir
from covtest.util.run import run
from test.benchmark.benchmark_utils import (
    setup_repo,
    apply_change,
    revert_change,
    get_broken_tests,
    get_predicted_tests,
    assert_benchmark,
)

DJANGO_TAG = "6.0.6"
DJANGO_REPO_URL = "https://github.com/django/django"

BREAKING_CHANGES = [
    {
        "id": "tree_py_negate",
        "file": "django/utils/tree.py",
        "line": 126,
        "original": "        self.negated = not self.negated\n",
        "replacement": "        kk\n",
        "description": "Breaking the utils tree negate",
    },
    {
        "id": "break_regex",
        "file": "django/utils/http.py",
        "line": 51,
        "original": '        query = query.lists()\n',
        "replacement": "        kk\n",
        "description": "Breaking regex_helper.py",
    }
]


def _django_setup(repo_dir: str, venv_python: str) -> None:  # noqa: ARG001
    """Write the config files that replace what runtests.py normally configures.

    Django's ``test_sqlite.py`` is a minimal settings file with no
    ``INSTALLED_APPS``.  ``runtests.py`` adds the test label (e.g. ``queries``)
    to ``INSTALLED_APPS`` at runtime before calling ``django.setup()``.  When
    using plain ``pytest`` we need a settings file that does the same thing
    statically — otherwise every model import raises:
        RuntimeError: Model class queries.models.X doesn't declare an explicit
        app_label and isn't in an application in INSTALLED_APPS.

    We write ``benchmark_settings.py`` next to ``test_sqlite.py`` (inside
    ``tests/``), which inherits everything from ``test_sqlite`` and adds the
    apps our test scope needs.  ``pytest.ini`` then points pytest-django at
    this custom settings module.
    """
    # Custom settings file: inherit test_sqlite + register the test app.
    settings_file = os.path.join(repo_dir, "tests", "benchmark_settings.py")
    with open(settings_file, "w") as f:
        f.write("# Auto-generated by covtest Django benchmark.\n")
        f.write("from test_sqlite import *  # noqa: F401, F403\n\n")
        f.write("INSTALLED_APPS = [\n")
        f.write("    'django.contrib.contenttypes',\n")
        f.write("    'django.contrib.auth',\n")
        f.write("    'queries',\n")
        f.write("]\n")

    # pytest.ini: tell pytest-django which settings to load and where to find them.
    pytest_ini = os.path.join(repo_dir, "pytest.ini")
    with open(pytest_ini, "w") as f:
        f.write("[pytest]\n")
        f.write("pythonpath = tests\n")
        f.write("DJANGO_SETTINGS_MODULE = benchmark_settings\n")

    with chdir(repo_dir):
        run("git add .")
        run("git commit -m add-ini")


@pytest.fixture(scope="module")
def django_repo(tmp_path_factory):
    return setup_repo(
        tmp_path_factory,
        tag=DJANGO_TAG,
        url=DJANGO_REPO_URL,
        pip_deps=[
            ("-e", "."),        # install Django itself in editable mode
            "pytest-django",
            "pytest-xdist",
            "pytest-timeout",
        ],
        test_scope="tests/queries/",
        cov_target="django",
        setup_hook=_django_setup,
        run_test_parallel=False)


@pytest.mark.benchmark
@pytest.mark.parametrize("change", BREAKING_CHANGES, ids=lambda c: c["id"])
def test_covtest_predicts_broken_tests(django_repo, change):
    repo_dir = django_repo["repo_dir"]
    venv_python = django_repo["venv_python"]
    try:
        apply_change(repo_dir, change)
        broken, total = get_broken_tests(
            repo_dir, venv_python, "tests/queries/",
            run_test_parallel=False
        )
        predicted = get_predicted_tests(repo_dir, venv_python)
        assert_benchmark(change, broken, total, predicted)
    finally:
        revert_change(repo_dir, change)
